const ALL_GREETINGS = [...GREETINGS, ...INSPIRATIONS];

let deck: string[] = [];

export function randomGreeting() {
  return ALL_GREETINGS[Math.floor(Math.random() * ALL_GREETINGS.length)];
}

export function nextInspiration() {
  if (deck.length === 0) {
    deck = [...INSPIRATIONS];
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
  }
  return deck.pop()!;
}
